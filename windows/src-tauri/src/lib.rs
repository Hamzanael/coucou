pub struct Shared {
    pub settings: Mutex<Settings>,
    pub gate: Arc<PollGate>,
    /// What the Worktrees view last showed: removal never reaches past it.
    pub last_scan: Mutex<Vec<worktrees::Stale>>,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BootInfo {
    settings: Settings,
    screen: ScreenInfo,
    version: String,
    hook_path: String,
    /// Set where the island stands in for the desktop's top-bar clock.
    clock: Option<ClockFormat>,
    /// The page tracks the mouse from its own events instead of the cursor poll.
    dom_pointer: bool,
}

#[tauri::command]
fn boot(app: AppHandle, shared: State<Shared>) -> BootInfo {
    let mut settings = shared.settings.lock().unwrap().clone();
    // The real state of ~/.claude/settings.json wins over whatever we stored.
    settings.hooks_installed = hooks::status().installed;
    let screen = island::screen_info(&app, &settings.screen);
    BootInfo {
        settings,
        screen,
        version: env!("CARGO_PKG_VERSION").to_string(),
        hook_path: settings::hook_exe_path().to_string_lossy().to_string(),
        clock: cfg!(target_os = "linux").then(calendar::clock_format),
        dom_pointer: cfg!(target_os = "linux"),
    }
}

#[tauri::command]
async fn calendar_events(since: i64, until: i64) -> Vec<CalendarEvent> {
    calendar::events(since, until).await
}

#[tauri::command]
fn save_settings(app: AppHandle, shared: State<Shared>, settings: Settings) {
    let (screen_changed, autostart_changed) = {
        let mut current = shared.settings.lock().unwrap();
        let screen_changed = current.screen != settings.screen;
        let autostart_changed = current.autostart != settings.autostart;
        *current = settings.clone();
        (screen_changed, autostart_changed)
    };
    if let Err(err) = settings::save(&settings) {
        eprintln!("[coucou] could not save settings: {err}");
    }
    if autostart_changed {
        let manager = app.autolaunch();
        let result = if settings.autostart { manager.enable() } else { manager.disable() };
        if let Err(err) = result {
            eprintln!("[coucou] autostart: {err}");
        }
    }
    if screen_changed {
        let collapsed = shared.gate.collapsed.load(Ordering::Relaxed);
        island::apply_geometry(&app, &settings.screen, collapsed);
    }
    // Keep the other window in step (island ⇄ settings window).
    let _ = app.emit("settings-changed", settings);
}

/// Hidden island → shrink the window to the invisible wake strip and park the
/// cursor poll; anything else → full panel and 60 Hz polling.
#[tauri::command]
fn set_collapsed(app: AppHandle, shared: State<Shared>, collapsed: bool) {
    let pref = shared.settings.lock().unwrap().screen.clone();
    island::apply_geometry(&app, &pref, collapsed);
    // The wake strip must always take the mouse, and a resize invalidates the flag.
    shared.gate.set_collapsed(&app, collapsed);
    shared.gate.set_active(!collapsed);
}

/// The front end pushes the island shape; Rust decides click-through from it.
#[tauri::command]
fn set_island_rect(app: AppHandle, shared: State<Shared>, x: f64, y: f64, width: f64, height: f64) {
    shared.gate.set_rect(island::IslandRect { x, y, w: width, h: height });
    // On Linux the window is the island: follow its size.
    if cfg!(target_os = "linux") {
        let pref = shared.settings.lock().unwrap().screen.clone();
        let collapsed = shared.gate.collapsed.load(Ordering::Relaxed);
        island::apply_geometry(&app, &pref, collapsed);
    }
}

#[tauri::command]
fn focus_window(app: AppHandle, focused: bool) {
    let Some(win) = island::window(&app) else { return };
    island::set_activating(&win, focused);
    #[cfg(not(target_os = "linux"))]
    if focused {
        let _ = win.set_focus();
    }
}

/// Linux: bar (pill / compact) ⇄ popup (expanded). No-op elsewhere.
#[tauri::command]
fn set_window_mode(app: AppHandle, popup: bool, focus: bool) {
    #[cfg(target_os = "linux")]
    if let Some(win) = island::window(&app) {
        island::set_popup(&win, popup, focus);
    }
    #[cfg(not(target_os = "linux"))]
    let _ = (app, popup, focus);
}

#[tauri::command]
fn reposition(app: AppHandle, shared: State<Shared>) {
    let pref = shared.settings.lock().unwrap().screen.clone();
    let collapsed = shared.gate.collapsed.load(Ordering::Relaxed);
    island::apply_geometry(&app, &pref, collapsed);
}

#[tauri::command]
fn open_url(url: String) {
    if !(url.starts_with("http://") || url.starts_with("https://")) {
        return;
    }
    platform::open_url(&url);
}

fn expand_home(p: &str) -> std::path::PathBuf {
    match p.strip_prefix("~/") {
        Some(rest) => platform::home().join(rest),
        None => std::path::PathBuf::from(p),
    }
}

#[tauri::command]
async fn worktrees_scan(shared: State<'_, Shared>) -> Result<Vec<worktrees::Stale>, String> {
    let (roots, days) = {
        let s = shared.settings.lock().unwrap();
        (s.worktree_roots.iter().map(|r| expand_home(r)).collect::<Vec<_>>(), s.worktree_idle_days)
    };
    let found = tauri::async_runtime::spawn_blocking(move || worktrees::scan(&roots, days))
        .await
        .map_err(|e| e.to_string())?;
    *shared.last_scan.lock().unwrap() = found.clone();
    Ok(found)
}

#[tauri::command]
async fn worktrees_remove(
    shared: State<'_, Shared>,
    paths: Vec<String>,
) -> Result<Vec<worktrees::Removal>, String> {
    let stale = shared.last_scan.lock().unwrap().clone();
    tauri::async_runtime::spawn_blocking(move || worktrees::remove(&stale, &paths))
        .await
        .map_err(|e| e.to_string())
}

/// "Open" on a session or the Claude pill: the project in IntelliJ, or the file
/// manager when no IntelliJ launcher is installed. The path is handed over as an
/// argument — no shell ever sees it.
#[tauri::command]
fn open_in_ide(path: Option<String>) -> bool {
    if ide::open(path.as_deref()) {
        return true;
    }
    if let Some(p) = path.as_deref().filter(|p| !p.is_empty()) {
        platform::open_folder(p);
    }
    false
}

/// Our own `where`: walks %PATH% against %PATHEXT%, no shell involved.
/// Rust quotes arguments correctly for `.cmd`/`.bat` targets since 1.77, so
/// spawning `code.cmd` directly is safe.
#[cfg(windows)]
pub(crate) fn find_on_path(stem: &str) -> Option<std::path::PathBuf> {
    let exts = std::env::var("PATHEXT").unwrap_or_else(|_| ".COM;.EXE;.BAT;.CMD".into());
    let dirs = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&dirs) {
        for ext in exts.split(';').filter(|e| !e.is_empty()) {
            let candidate = dir.join(format!("{stem}{}", ext.to_lowercase()));
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}

/// `which`, without a shell: the first executable file called `stem` on $PATH.
#[cfg(not(windows))]
pub(crate) fn find_on_path(stem: &str) -> Option<std::path::PathBuf> {
    use std::os::unix::fs::PermissionsExt;
    let dirs = std::env::var_os("PATH")?;
    std::env::split_paths(&dirs)
        .map(|dir| dir.join(stem))
        .find(|p| {
            std::fs::metadata(p)
                .map(|m| m.is_file() && m.permissions().mode() & 0o111 != 0)
                .unwrap_or(false)
        })
}

